/* numeros.js - Metodos de math y number */

console.log(Math.round(4.6));                       /* Redondea a 5 */
console.log(Math.floor(4.6));                       /* redondea a 4 (hacia abajo) */
console.log(Math.ceil(4.2));                        /* Redindea 5 (hacia arriba) */
console.log(Math.max(45000, 75000, 38000));         /* Encuentra el mayor */
console.log(Math.min(45000, 75000, 38000));         /* Encuentra el menor */
console.log(Number.isInteger(2.75));                /* Pregunta: ¿es entero? */
