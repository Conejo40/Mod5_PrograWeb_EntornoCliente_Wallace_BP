/* operadores.js - Aritmetricos y de asignacion */
const precio = 45000; /* Retrato individual */
console.log(precio + 5000); /* suma */
console.log(precio - 5000); /* resta */
console.log(precio * 2); /* multiplicacion */
console.log(precio / 2); /* division */
console.log(7 % 2); /* residuo de 7 / 2 */
let total = 0; /* Variable empieza en 0 */
total += precio; /* igual que total = total + precio */
console.log(total); /* 45000 */
